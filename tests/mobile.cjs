const {chromium}=require('C:/Users/leori/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(String(e)));
  const source=fs.readFileSync('game.js','utf8').replace('requestAnimationFrame(frame);\n})();',"window.mobileTest={state:()=>({mode,x:player.x,y:player.y,dash:player.dashCd,nova:player.novaCd,stick:{...stick}})};requestAnimationFrame(frame);\n})();");
  await page.route(/game\.js/,route=>route.fulfill({contentType:'application/javascript',body:source}));
  await page.goto('file:///C:/Games/KillMe2/index.html');
  await page.waitForSelector('.hero-card');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#startButton').tap();
  const cdp=await context.newCDPSession(page);
  const box=await page.locator('#joystick').boundingBox();
  const origin={x:box.x+box.width/2,y:box.y+box.height/2,id:1};
  const state=()=>page.evaluate(()=>mobileTest.state());
  const before=await state();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[origin]});
  const moved={...origin,x:origin.x+38};
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[moved]});
  await page.waitForTimeout(150);
  assert.ok((await state()).x>before.x+10,'touch moves player');
  const dash=await page.locator('#dashButton').boundingBox();
  const second={x:dash.x+dash.width/2,y:dash.y+dash.height/2,id:2};
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[moved,second]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[second]});
  await page.waitForTimeout(60);
  assert.ok((await state()).dash>0,'second finger activates dash while moving');
  assert.ok((await state()).stick.x>0,'movement continues with second finger');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchCancel',touchPoints:[]});
  assert.equal((await state()).stick.x,0,'cancel releases movement');
  const floatingOrigin={x:100,y:500,id:3};
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[floatingOrigin]});
  assert.equal((await state()).stick.cx,100,'stick starts at the finger outside its resting position');
  assert.equal((await state()).stick.x,0,'initial contact stays neutral');
  const dragged={...floatingOrigin,x:200};
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[dragged]});
  const floating=await state();
  assert.ok(floating.stick.cx>150,'base follows a long drag');
  assert.ok(floating.stick.x>.99,'long drag keeps full movement');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{...dragged,x:145}]});
  await page.waitForTimeout(50);
  assert.ok((await state()).stick.x<0,'can reverse without returning to the initial touch');
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  assert.equal((await state()).stick.id,null,'lifting the finger releases movement');
  assert.equal(await page.locator('#joystick').evaluate(e=>e.style.top),'','resting position restored');
  await page.locator('#novaButton').tap();assert.ok((await state()).nova>0);
  await page.screenshot({path:'tests/touch-portrait.png'});
  await page.setViewportSize({width:844,height:390});
  await page.waitForTimeout(100);
  const joystick=await page.locator('#joystick').boundingBox(),abilities=await page.locator('.abilities').boundingBox();
  assert.ok(joystick.x+joystick.width<abilities.x,'controls do not overlap');
  await page.screenshot({path:'tests/touch-landscape.png'});
  await page.locator('#pauseButton').tap();assert.equal((await state()).mode,'pause');
  assert.equal((await state()).stick.x,0);
  await page.locator('#continueButton').tap();assert.equal((await state()).mode,'play');
  await page.locator('#quickSettingsButton').tap();
  await page.locator('#fullscreenButton').tap();
  await page.waitForFunction(()=>!!document.fullscreenElement);
  assert.equal(await page.locator('#fullscreenButton').getAttribute('aria-pressed'),'true');
  await page.evaluate(()=>document.exitFullscreen());
  await page.waitForFunction(()=>!document.fullscreenElement&&document.getElementById('fullscreenButton').getAttribute('aria-pressed')==='false');
  assert.equal(await page.locator('#fullscreenButton').getAttribute('aria-pressed'),'false');
  await page.evaluate(()=>{document.documentElement.requestFullscreen=undefined;document.documentElement.webkitRequestFullscreen=undefined;});
  await page.locator('#fullscreenButton').tap();assert.equal(await page.locator('#displayNotice').isVisible(),true);
  await page.locator('#closeSettingsButton').tap();
  await page.setViewportSize({width:320,height:568});
  await page.locator('#pauseButton').tap();await page.locator('#homeButton').tap();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  assert.equal(await page.evaluate(()=>getComputedStyle(document.body).overflow!=='hidden'),true,'menu scroll restored');
  assert.deepEqual(errors,[]);
  console.log('PASS: touch movement, multitouch dash, super, cancellation, pause/resume, portrait/landscape, fullscreen entry/exit/fallback and 320px menu.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
